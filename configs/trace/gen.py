#!/usr/bin/env python3
"""重新生成 barectf C 源码与 CTF metadata。

用法：
    python configs/trace/gen.py

依赖：pip install barectf==3.1.2
产物：vendor/barectf/{barectf.c,barectf.h,barectf-bitfield.h,metadata}
生成后的 C 代码已提交到仓库，未安装 barectf 也能正常构建。
"""

import os
import shutil
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
CFG = os.path.join(ROOT, "configs", "trace", "iot-trace.yaml")
OUT = os.path.join(ROOT, "vendor", "barectf")


def main():
    exe = shutil.which("barectf")
    if exe is None:
        print("error: barectf not found; run `pip install barectf==3.1.2`", file=sys.stderr)
        return 1

    os.makedirs(OUT, exist_ok=True)
    cmd = [
        exe, "generate",
        "--code-dir=" + OUT,
        "--headers-dir=" + OUT,
        "--metadata-dir=" + OUT,
        CFG,
    ]
    print(" ".join(cmd))

    # barectf opens YAML with the platform default encoding (GBK on zh-CN
    # Windows); force UTF-8 so the generator is locale-independent.
    env = dict(os.environ)
    env["PYTHONUTF8"] = "1"
    env["PYTHONIOENCODING"] = "utf-8"
    rc = subprocess.call(cmd, env=env)
    if rc != 0:
        return rc

    # Generated barectf.c contains a helper that is unused when no string
    # fields are configured. Silence that warning without patching each build.
    code_path = os.path.join(OUT, "barectf.c")
    with open(code_path, encoding="utf-8") as f:
        code = f.read()
    pragma = ('#if defined(__GNUC__)\n'
              '#pragma GCC diagnostic ignored "-Wunused-function"\n'
              '#endif\n')
    if pragma not in code:
        code = code.replace("#include <stdint.h>",
                            pragma + "\n#include <stdint.h>", 1)
        with open(code_path, "w", encoding="utf-8", newline="\n") as f:
            f.write(code)

    for name in ("barectf.c", "barectf.h", "barectf-bitfield.h", "metadata"):
        path = os.path.join(OUT, name)
        print("  generated %-24s %d bytes" % (name, os.path.getsize(path)))

    # Emit the CTF metadata as a C string header so the PC backend can
    # write it next to the binary stream file (no runtime file dependency).
    meta_path = os.path.join(OUT, "metadata")
    with open(meta_path, encoding="utf-8") as f:
        meta = f.read()
    esc = (meta.replace("\\", "\\\\")
               .replace('"', '\\"')
               .replace("\r", "")
               .replace("\n", "\\n"))
    header_path = os.path.join(OUT, "metadata.h")
    with open(header_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(
            "/* Generated by configs/trace/gen.py - do not edit. */\n"
            "#ifndef BARECTF_METADATA_H\n"
            "#define BARECTF_METADATA_H\n"
            "static const char *g_iot_barectf_metadata =\n"
            '    "' + esc + '";\n'
            "#endif\n"
        )
    print("  generated %-24s %d bytes" % ("metadata.h", os.path.getsize(header_path)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
