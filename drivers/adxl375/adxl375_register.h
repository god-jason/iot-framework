#ifndef ADXL375_REGISTER_H
#define ADXL375_REGISTER_H

/* ADXL375 高 g 三轴加速度计寄存器与常量（寄存器布局与 ADXL345 兼容） */

#define ADXL375_DEFAULT_ADDRESS     0x53U
#define ADXL375_ADDRESS_ALT         0x1DU

#define ADXL375_REG_DEVID           0x00U
#define ADXL375_REG_THRESH_TAP      0x1DU
#define ADXL375_REG_OFSX            0x1EU
#define ADXL375_REG_OFSY            0x1FU
#define ADXL375_REG_OFSZ            0x20U
#define ADXL375_REG_DUR             0x21U
#define ADXL375_REG_LATENT          0x22U
#define ADXL375_REG_WINDOW          0x23U
#define ADXL375_REG_THRESH_ACT      0x24U
#define ADXL375_REG_THRESH_INACT    0x25U
#define ADXL375_REG_TIME_INACT      0x26U
#define ADXL375_REG_ACT_INACT_CTL   0x27U
#define ADXL375_REG_THRESH_FF       0x28U
#define ADXL375_REG_TIME_FF         0x29U
#define ADXL375_REG_TAP_AXES        0x2AU
#define ADXL375_REG_ACT_TAP_STATUS  0x2BU
#define ADXL375_REG_BW_RATE         0x2CU
#define ADXL375_REG_POWER_CTL       0x2DU
#define ADXL375_REG_INT_ENABLE      0x2EU
#define ADXL375_REG_INT_MAP         0x2FU
#define ADXL375_REG_INT_SOURCE      0x30U
#define ADXL375_REG_DATA_FORMAT     0x31U
#define ADXL375_REG_DATAX0          0x32U
#define ADXL375_REG_DATAX1          0x33U
#define ADXL375_REG_DATAY0          0x34U
#define ADXL375_REG_DATAY1          0x35U
#define ADXL375_REG_DATAZ0          0x36U
#define ADXL375_REG_DATAZ1          0x37U
#define ADXL375_REG_FIFO_CTL        0x38U
#define ADXL375_REG_FIFO_STATUS     0x39U

#define ADXL375_DEVID_VALUE         0xE5U

/* POWER_CTL：bit3 进入测量模式 */
#define ADXL375_POWER_MEASURE       0x08U
#define ADXL375_POWER_STANDBY       0x00U

/* DATA_FORMAT：全分辨率 + 量程位（±200g 固定） */
#define ADXL375_FORMAT_FULL_RES     0x08U
#define ADXL375_FORMAT_RANGE_200G   0x03U
#define ADXL375_FORMAT_DEFAULT      (ADXL375_FORMAT_FULL_RES | ADXL375_FORMAT_RANGE_200G)

/* BW_RATE：低 4 位为输出率编码 */
#define ADXL375_BW_RATE_MASK        0x0FU
#define ADXL375_BW_RATE_100HZ       0x0AU
#define ADXL375_BW_RATE_200HZ       0x0BU
#define ADXL375_BW_RATE_400HZ       0x0CU
#define ADXL375_BW_RATE_800HZ       0x0DU
#define ADXL375_BW_RATE_1600HZ      0x0EU
#define ADXL375_BW_RATE_3200HZ      0x0FU

/* INT_SOURCE / INT_ENABLE */
#define ADXL375_INT_DATA_READY      0x80U
#define ADXL375_INT_OVERRUN         0x01U

/* 灵敏度：±200g 量程 20.5 LSB/g（约 49 mg/LSB） */
#define ADXL375_LSB_PER_G           20.5f

/* 总线标志 */
#define ADXL375_SPI_READ            0x80U
#define ADXL375_SPI_MULTI_BYTE      0x40U
#define ADXL375_BURST_MAX           8U

#define ADXL375_BOOT_DELAY_MS       10U

#endif /* ADXL375_REGISTER_H */
