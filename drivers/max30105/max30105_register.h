#ifndef MAX30105_REGISTER_H
#define MAX30105_REGISTER_H

/* MAX30105 心率 / 血氧 / 颗粒物传感器寄存器定义（I2C 0x57） */

#define MAX30105_ADDRESS_DEFAULT        0x57U
#define MAX30105_PART_ID_VALUE          0x15U

/* 寄存器 */
#define MAX30105_REG_INTR_STATUS_1      0x00U
#define MAX30105_REG_INTR_STATUS_2      0x01U
#define MAX30105_REG_INTR_ENABLE_1      0x02U
#define MAX30105_REG_INTR_ENABLE_2      0x03U
#define MAX30105_REG_FIFO_WR_PTR        0x04U
#define MAX30105_REG_OVF_COUNTER        0x05U
#define MAX30105_REG_FIFO_RD_PTR        0x06U
#define MAX30105_REG_FIFO_DATA          0x07U
#define MAX30105_REG_FIFO_CONFIG        0x08U
#define MAX30105_REG_MODE_CONFIG        0x09U
#define MAX30105_REG_SPO2_CONFIG        0x0AU
#define MAX30105_REG_LED1_PA            0x0CU  /* RED */
#define MAX30105_REG_LED2_PA            0x0DU  /* IR */
#define MAX30105_REG_LED3_PA            0x0EU  /* GREEN */
#define MAX30105_REG_PILOT_PA           0x10U
#define MAX30105_REG_MULTI_LED_CTRL1    0x11U
#define MAX30105_REG_MULTI_LED_CTRL2    0x12U
#define MAX30105_REG_TEMP_INTR          0x1FU
#define MAX30105_REG_TEMP_FRAC          0x20U
#define MAX30105_REG_TEMP_CONFIG        0x21U
#define MAX30105_REG_PROX_INT_THRESH    0x30U
#define MAX30105_REG_REV_ID             0xFEU
#define MAX30105_REG_PART_ID            0xFFU

/* MODE_CONFIG 位 */
#define MAX30105_MODE_SHUTDOWN          0x80U
#define MAX30105_MODE_RESET             0x40U

/* FIFO_CONFIG 位 */
#define MAX30105_FIFO_ROLLOVER_EN       0x10U
#define MAX30105_FIFO_A_FULL_MASK       0x0FU
#define MAX30105_FIFO_A_FULL_15         0x0FU

/* SPO2_CONFIG 位 */
#define MAX30105_SPO2_ADC_RANGE_4096    0x20U
#define MAX30105_SPO2_SR_400HZ          0x0CU  /* 采样率 400Hz << 2 */
#define MAX30105_SPO2_PW_411US_18BIT    0x03U

/* FIFO / 采样 */
#define MAX30105_FIFO_DEPTH             32U
#define MAX30105_SAMPLE_BYTES_PER_CH    3U
#define MAX30105_MAX_CHANNELS           3U
#define MAX30105_FIFO_MAX_BYTES         (MAX30105_FIFO_DEPTH * MAX30105_SAMPLE_BYTES_PER_CH * \
                                         MAX30105_MAX_CHANNELS)
#define MAX30105_FIFO_PTR_MASK          0x1FU
#define MAX30105_ADC_MASK               0x03FFFFUL

/* 温度 */
#define MAX30105_TEMP_FRAC_LSB_C        0.0625f
#define MAX30105_TEMP_MEASURE_MS        30U

#endif /* MAX30105_REGISTER_H */
