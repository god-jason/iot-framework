#ifndef SSD1315_REGISTER_H
#define SSD1315_REGISTER_H

/*
 * SSD1315 命令定义（兼容 SSD1306 命令集，128x64 单色 OLED）。
 * 参数需按面板调整：对比度、预充电、VCOMH 因玻璃厂商而异。
 */

#define SSD1315_DEFAULT_I2C_ADDRESS 0x3CU
#define SSD1315_I2C_ADDRESS_ALT     0x3DU

#define SSD1315_WIDTH               128U
#define SSD1315_HEIGHT              64U
#define SSD1315_PAGES               (SSD1315_HEIGHT / 8U)
#define SSD1315_GRAM_SIZE           (SSD1315_WIDTH * SSD1315_PAGES)

/* I2C 控制字节 */
#define SSD1315_CTRL_CMD            0x00U
#define SSD1315_CTRL_DATA           0x40U

/* 基础命令 */
#define SSD1315_CMD_DISPLAY_OFF     0xAEU
#define SSD1315_CMD_DISPLAY_ON      0xAFU
#define SSD1315_CMD_SET_CONTRAST    0x81U
#define SSD1315_CMD_ENTIRE_ON       0xA4U
#define SSD1315_CMD_NORMAL_DISPLAY  0xA6U
#define SSD1315_CMD_INVERT_DISPLAY  0xA7U

#define SSD1315_CMD_SET_MUX         0xA8U
#define SSD1315_CMD_SET_OFFSET      0xD3U
#define SSD1315_CMD_SET_START_LINE  0x40U
#define SSD1315_CMD_SEG_REMAP       0xA1U
#define SSD1315_CMD_COM_SCAN_DEC    0xC8U
#define SSD1315_CMD_COM_SCAN_INC    0xC0U
#define SSD1315_CMD_COM_PINS        0xDAU
#define SSD1315_CMD_SET_CLOCK       0xD5U
#define SSD1315_CMD_SET_PRECHARGE   0xD9U
#define SSD1315_CMD_SET_VCOM        0xDBU
#define SSD1315_CMD_CHARGE_PUMP     0x8DU
#define SSD1315_CMD_ADDR_MODE       0x20U
#define SSD1315_CMD_DEACT_SCROLL    0x2EU

/* 页寻址 */
#define SSD1315_CMD_PAGE_START      0xB0U
#define SSD1315_CMD_COL_LOW         0x00U
#define SSD1315_CMD_COL_HIGH        0x10U

#define SSD1315_ADDR_MODE_PAGE      0x02U

/* 初始化参数：参数需按面板调整 */
#define SSD1315_MUX_RATIO_64        0x3FU
#define SSD1315_COM_PINS_64         0x12U
#define SSD1315_CLOCK_DIV           0x80U
#define SSD1315_PRECHARGE           0xF1U
#define SSD1315_VCOM_DESELECT       0x40U
#define SSD1315_CHARGE_PUMP_ON      0x14U
#define SSD1315_CONTRAST_DEFAULT    0xCFU

#define SSD1315_RESET_LOW_MS        10U
#define SSD1315_RESET_WAIT_MS       10U

#endif /* SSD1315_REGISTER_H */
